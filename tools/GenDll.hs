-- | 生成 DLL 的三份产物（唯一的代码生成器，build-dll.ps1 会先跑它）：
module Main (main) where

import Data.Char (toLower)
import System.Environment (getArgs)
import System.IO (IOMode (..), hClose, hPutStr, hSetEncoding, openFile, utf8)

import OmegaY.Dll (symbolOf)
import OmegaY.Notation.Types (Caps (..), Notation (..))
import OmegaY.Registry (allNotations)

data Entry = Entry
  { eId :: String
  , eSym :: String
  , eKind :: String
  , eParam :: Maybe (Int, Int, Int)
  }

mkEntry :: Notation -> Entry
mkEntry n =
  Entry
    { eId = nId n
    , eSym = symbolOf (nId n)
    , eKind = kindStr
    , eParam = prm
    }
  where
    (kindStr, prm) = case nCaps n of
      SeqCaps {} -> ("seq", Nothing)
      TextCaps {} -> ("text", Nothing)
      ParamCaps {} -> ("param", fmap (\(mn, mx, d, _) -> (mn, mx, d)) (nParam n))

entries :: [Entry]
entries = map mkEntry allNotations

cArgs :: Entry -> String
cArgs e = case eKind e of
  "param" -> "const char * input, int term, int param"
  _ -> "const char * input, int term"

hsName :: String -> String
hsName sym = "w_" ++ map toLower sym

hsModule :: [Entry] -> String
hsModule es =
  unlines $
    [ "{-# LANGUAGE ForeignFunctionInterface #-}"
    , "-- | 自动生成：每个记号两个 C 入口（fs / alter）。生成器 tools/GenDll.hs，请勿手改。"
    , "module Expander2Exports where"
    , ""
    , "import Foreign.C.String (CString)"
    -- CInt 的构造器必须一起导进来，否则 FFI 类型检查报
    -- "CInt cannot be marshalled in a foreign call because its data constructor is not in scope"
    , "import Foreign.C.Types (CInt (..))"
    , "import OmegaY.Dll (expandWith)"
    ]
      ++ concatMap hsBlock es

hsBlock :: Entry -> [String]
hsBlock e =
  [ ""
  , "-- | " ++ eSym e ++ "  (id: " ++ eId e ++ ", kind: " ++ eKind e ++ ")"
  , hsName (eSym e) ++ "_fs :: " ++ hsSig
  , hsName (eSym e) ++ "_fs " ++ hsParams 0
  , ""
  , hsName (eSym e) ++ "_alt :: " ++ hsSig
  , hsName (eSym e) ++ "_alt " ++ hsParams 1
  , ""
  , "foreign export ccall \"" ++ eSym e ++ "\" " ++ hsName (eSym e) ++ "_fs :: " ++ hsSig
  , "foreign export ccall \"" ++ eSym e ++ "_ALTER\" " ++ hsName (eSym e) ++ "_alt :: " ++ hsSig
  ]
  where
    hsSig = case eKind e of
      "param" -> "CString -> CInt -> CInt -> IO CString"
      _ -> "CString -> CInt -> IO CString"

    hsParams mode = case eKind e of
      "param" ->
        "cs term param = expandWith \""
          ++ eId e ++ "\" " ++ show mode ++ " cs (fromIntegral term) (fromIntegral param)"
      _ ->
        "cs term = expandWith \""
          ++ eId e ++ "\" " ++ show mode ++ " cs (fromIntegral term) 0"

cHeader :: [Entry] -> String
cHeader es =
  unlines $
    [ "/* expander2.h -- C ABI of the expander2.haskell computation layer"
    , " * (Windows x64 DLL, built by GHC)."
    , " *"
    , " * GENERATED by tools/GenDll.hs -- do not edit by hand."
    , " * notations: " ++ show (length es) ++ ", per-notation entries: " ++ show (2 * length es)
    , " *"
    , " * Lifetime"
    , " *   Every char* returned here is malloc'd on the Haskell side and MUST be"
    , " *   released with EXPANDER2_FREE(). Never call free() on it."
    , " *   NULL means failure; the message comes from EXPANDER2_LAST_ERROR()"
    , " *   (errno style: process-global, not thread-local, copied on each read)."
    , " *"
    , " * Input"
    , " *   input is a UTF-8 expression, the same text the CLI reads from stdin."
    , " *   NULL is treated as an empty expression. term / param mirror the CLI"
    , " *   arguments (term is 1-based; param is ignored by non-param notations)."
    , " *"
    , " * Modes"
    , " *   SYMBOL        -> mode fs    (the CLI's  <id> fs ...)"
    , " *   SYMBOL_ALTER  -> mode alter (the CLI's  <id> alter ...)"
    , " *"
    , " * Symbol naming"
    , " *   id upper-cased, every char outside [0-9A-Za-z] becomes '_', runs of '_'"
    , " *   collapsed, a leading '_' is added if the name would start with a digit."
    , " *   e.g. pps -> PPS, bms-v1 -> BMS_V1, -1y-(n+1)ss -> _1Y_N_1_SS"
    , " *"
    , " * RTS"
    , " *   Call hs_init(&argc, &argv) before the first use and hs_exit() before"
    , " *   unloading. Load one flavour only (llvm or compat) per process."
    , " */"
    , ""
    , "#ifndef EXPANDER2_H"
    , "#define EXPANDER2_H"
    , ""
    , "#ifdef __cplusplus"
    , "extern \"C\" {"
    , "#endif"
    , ""
    , "#if defined(_WIN32) || defined(__CYGWIN__)"
    , "#  ifdef EXPANDER2_BUILD"
    , "#    define EXPANDER2_API __declspec(dllexport)"
    , "#  else"
    , "#    define EXPANDER2_API __declspec(dllimport)"
    , "#  endif"
    , "#else"
    , "#  define EXPANDER2_API"
    , "#endif"
    , ""
    , "#define EXPANDER2_MODE_FS     0"
    , "#define EXPANDER2_MODE_ALTER  1"
    , ""
    , "#define EXPANDER2_KIND_SEQ    0"
    , "#define EXPANDER2_KIND_TEXT   1"
    , "#define EXPANDER2_KIND_PARAM  2"
    , ""
    , "/* --- GHC RTS, linked into the DLL --- */"
    , "EXPANDER2_API void hs_init(int * argc, char ** argv[]);"
    , "EXPANDER2_API void hs_exit(void);"
    , ""
    , "/* --- generic entry --- */"
    , "EXPANDER2_API char * EXPANDER2_EXPAND(const char * id, int mode, int term, int param, const char * input);"
    , "EXPANDER2_API void   EXPANDER2_FREE(char * s);"
    , "EXPANDER2_API char * EXPANDER2_LAST_ERROR(void);"
    , "EXPANDER2_API char * EXPANDER2_BUILD(void);"
    , ""
    , "/* --- registry introspection (index 0 .. EXPANDER2_COUNT()-1) --- */"
    , "EXPANDER2_API int    EXPANDER2_COUNT(void);"
    , "EXPANDER2_API char * EXPANDER2_ID(int index);"
    , "EXPANDER2_API char * EXPANDER2_NAME(int index);"
    , "EXPANDER2_API char * EXPANDER2_SYMBOL(int index);"
    , "EXPANDER2_API int    EXPANDER2_KIND(int index);"
    , "EXPANDER2_API int    EXPANDER2_PARAM_MIN(int index);"
    , "EXPANDER2_API int    EXPANDER2_PARAM_MAX(int index);"
    , "EXPANDER2_API int    EXPANDER2_PARAM_DEFAULT(int index);"
    ]
      ++ concatMap hdrBlock es
      ++ [ ""
         , "#ifdef __cplusplus"
         , "}"
         , "#endif"
         , ""
         , "#endif /* EXPANDER2_H */"
         ]

hdrBlock :: Entry -> [String]
hdrBlock e =
  [ ""
  , "/* ---- id=" ++ eId e ++ " kind=" ++ eKind e ++ prmNote ++ " ---- */"
  , "EXPANDER2_API char * " ++ eSym e ++ "(" ++ cArgs e ++ ");"
  , "EXPANDER2_API char * " ++ eSym e ++ "_ALTER(" ++ cArgs e ++ ");"
  ]
  where
    prmNote = case eParam e of
      Just (mn, mx, d) -> " param=" ++ show mn ++ ".." ++ show mx ++ " default=" ++ show d
      Nothing -> ""

-- | .def 用的符号清单（一symbol 一行，build 脚本再套 LIBRARY/EXPORTS 头）
symbolList :: [Entry] -> String
symbolList es =
  unlines $
    [ "EXPANDER2_EXPAND"
    , "EXPANDER2_FREE"
    , "EXPANDER2_LAST_ERROR"
    , "EXPANDER2_BUILD"
    , "EXPANDER2_COUNT"
    , "EXPANDER2_ID"
    , "EXPANDER2_NAME"
    , "EXPANDER2_SYMBOL"
    , "EXPANDER2_KIND"
    , "EXPANDER2_PARAM_MIN"
    , "EXPANDER2_PARAM_MAX"
    , "EXPANDER2_PARAM_DEFAULT"
    , "hs_init"
    , "hs_exit"
    ]
      ++ concatMap (\e -> [eSym e, eSym e ++ "_ALTER"]) es

writeUtf8 :: FilePath -> String -> IO ()
writeUtf8 path content = do
  h <- openFile path WriteMode
  hSetEncoding h utf8
  hPutStr h content
  hClose h

main :: IO ()
main = do
  args <- getArgs
  outDir <- case args of
    [d] | not (null d) && last d `elem` "\\/" -> pure d
    _ -> error "usage: gen-dll <outdir>   (outdir must end with \\ or /)"
  let es = entries
      syms = map eSym es
      dupSyms = [s | s <- syms, length (filter (== s) syms) > 1]
  if null dupSyms
    then pure ()
    else error ("导出符号名撞车（同一符号对应多个 id）：" ++ show dupSyms)

  writeUtf8 (outDir ++ "Expander2Exports.hs") (hsModule es)
  writeUtf8 (outDir ++ "expander2.h") (cHeader es)
  writeUtf8 (outDir ++ "symbols.txt") (symbolList es)

  putStrLn $
    "generated: " ++ show (length es) ++ " notations, "
      ++ show (2 * length es + 14) ++ " exported symbols"
